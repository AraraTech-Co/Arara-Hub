import * as React from "react"
import { cn } from "@/lib/utils"

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      // Elevação no lugar da borda. O shadcn cru põe 1px em volta de todo
      // bloco: numa tela de admin com vinte cartões são vinte arestas que o
      // olho refixa sem querer. A sombra separa pelo mesmo motivo e não
      // desenha linha. Mesmo tratamento dos painéis do inbox, que é o mundo
      // aprovado. A borda continua legítima em pílula pequena — 1px num chip
      // de 20px é a própria forma, não moldura.
      "rounded-lg bg-card text-card-foreground shadow-[var(--shadow-media)]",
      className
    )}
    {...props}
  />
))
Card.displayName = "Card"

